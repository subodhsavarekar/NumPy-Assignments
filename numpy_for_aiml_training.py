print(f"arr         = {arr}          shape: {arr.shape}")
print(f"arr + 10    = {arr + 10}     ← 10 broadcast to every element")
print(f"arr * 3     = {arr * 3}      ← 3  broadcast to every element")
print(f"arr ** 2    = {arr ** 2}  ← each element squared")

# --- 1D array broadcast over 2D array ---
print("\n=== 1D broadcast over 2D ===")
