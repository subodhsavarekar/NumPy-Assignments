"""---
# Section 4: Indexing & Slicing

**Indexing** = picking one element.  
**Slicing** = picking a range of elements.

This is how you **access, inspect, and extract** data from arrays — a daily task in any ML pipeline.

---

## 4.1 1D Indexing & Slicing

```
arr  =  [10, 20, 30, 40, 50, 60]
index:    0   1   2   3   4   5
         -6  -5  -4  -3  -2  -1   ← negative counts from the end
```

| Syntax | Meaning |
|--------|---------|
| `arr[2]` | Element at index 2 → `30` |
| `arr[-1]` | Last element → `60` |
| `arr[1:4]` | Indices 1, 2, 3 → `[20, 30, 40]` |
| `arr[::2]` | Every 2nd element → `[10, 30, 50]` |
| `arr[::-1]` | Reverse the array |

---

## 4.2 2D Indexing & Slicing

Think of a 2D array like a **spreadsheet** — `arr[row, col]`.

```
arr[0, 2]        → single element: row 0, col 2
arr[1, :]        → entire row 1
arr[:, 2]        → entire column 2
arr[0:2, 1:3]    → sub-matrix: rows 0-1, cols 1-2
```

---

## 4.3 Views vs Copies — Important!

> Slices return a **view** (not a copy). Modifying a slice modifies the original array!  
> Use `.copy()` when you want a separate copy.
"""

# ============================================================
# SECTION 4 — Example 1: 1D indexing and slicing
# ============================================================

arr = np.array([10, 20, 30, 40, 50, 60])
print("Array:", arr)

# --- Positive indexing (left to right, starts at 0) ---
print("\n=== Positive indexing ===")
print("arr[0]  =", arr[0])   # first element
print("arr[2]  =", arr[2])   # third element
print("arr[5]  =", arr[5])   # last element (index 5)

# --- Negative indexing (right to left, starts at -1) ---
print("\n=== Negative indexing ===")
print("arr[-1] =", arr[-1])  # last element
print("arr[-2] =", arr[-2])  # second to last
print("arr[-6] =", arr[-6])  # same as arr[0]

# --- Slicing: arr[start : stop : step] ---
# stop is EXCLUSIVE — arr[1:4] gives indices 1, 2, 3 (NOT 4)
print("\n=== Slicing ===")
print("arr[1:4]   =", arr[1:4])    # indices 1,2,3  → [20, 30, 40]
print("arr[:3]    =", arr[:3])     # from start to index 2 → [10, 20, 30]
print("arr[3:]    =", arr[3:])     # from index 3 to end   → [40, 50, 60]
print("arr[::2]   =", arr[::2])    # every 2nd element     → [10, 30, 50]
print("arr[1::2]  =", arr[1::2])   # start at 1, every 2nd → [20, 40, 60]
print("arr[::-1]  =", arr[::-1])   # reverse the array     → [60, 50, 40, 30, 20, 10]

# --- View vs Copy ---
print("\n=== View vs Copy ===")
original  = np.array([1, 2, 3, 4, 5])
view_arr  = original[1:4]       # this is a VIEW — shares memory
copy_arr  = original[1:4].copy() # this is a COPY — independent

view_arr[0] = 999               # modifies original!
print("After view_arr[0] = 999:")
print("  original =", original)  # [1, 999, 3, 4, 5] — changed!

copy_arr[0] = 888               # does NOT modify original
print("After copy_arr[0] = 888:")
print("  original =", original)  # still [1, 999, 3, 4, 5]

