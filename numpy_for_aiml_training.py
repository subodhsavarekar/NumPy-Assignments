"""---
# Section 7: Broadcasting

**Broadcasting** is NumPy's rule for performing operations on arrays with **different shapes** — without copying data or writing loops.

It is one of the most powerful (and often confusing!) features of NumPy. Once you understand it, your code becomes shorter, faster, and more readable.

---

## 7.1 The Basic Idea

When you add a scalar to an array, NumPy "stretches" the scalar to match the array's shape:

```
[1, 2, 3] + 10  →  [11, 12, 13]
```

NumPy did NOT create a new array `[10, 10, 10]` in memory — it just **acts as if** it did.

---

## 7.2 Broadcasting Rules

NumPy compares shapes **right to left**. Two dimensions are compatible if:
1. They are **equal**, OR  
2. One of them is **1**

```
Shape A:  (3, 4)      Shape A:  (1, 4)      Shape A:  (3, 1)
Shape B:     (4)      Shape B:  (3, 4)      Shape B:  (1, 4)
Result :  (3, 4) ✅   Result :  (3, 4) ✅   Result :  (3, 4) ✅

Shape A:  (3, 4)
Shape B:  (3, 3)
Result :  ERROR ❌  (4 ≠ 3, neither is 1)
```

---

## 7.3 Real-World Broadcasting in ML

- **Normalising features**: subtract mean from every row  
  `data - data.mean(axis=0)` → (100, 5) − (5,) → works!
- **Adding bias** to a weight matrix output  
  `(batch, output) + (output,)` → broadcasts the bias vector

---

> **Tip:** When in doubt, check `.shape` before the operation and apply the rules above.
"""

